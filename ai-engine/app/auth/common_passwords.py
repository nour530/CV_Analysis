_LEET_TRANSLATION = str.maketrans(
    {
        "0": "o",
        "1": "i",
        "3": "e",
        "4": "a",
        "5": "s",
        "7": "t",
        "@": "a",
        "$": "s",
        "!": "i",
    }
)
_NON_ALPHANUMERIC = re.compile(r"[^a-z0-9]+")


def _compact(value: str) -> str:
    return _NON_ALPHANUMERIC.sub("", value.casefold())


def is_common_password(password: str) -> bool:
    normalized = password.strip().casefold()
    compact = _compact(normalized)
    leet_normalized = _compact(normalized.translate(_LEET_TRANSLATION))
    candidates = {normalized, compact, leet_normalized}
    if any(candidate in COMMON_PASSWORDS for candidate in candidates):
        return True
    if len(compact) < 8:
        return False
    return any(
        part in candidate
        for candidate in (compact, leet_normalized)
        for part in COMMON_PASSWORD_PARTS
    )
